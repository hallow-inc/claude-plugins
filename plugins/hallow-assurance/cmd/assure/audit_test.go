func TestAuditAdapterRoleConflictExitsOne(t *testing.T) {
	auditRepo(t, "version: 0\ncatalog: v0\nlanguages: [go, zz]\ndefault_level: B\ncomponents: []\n")
	bin := t.TempDir()
	script := `#!/bin/sh
[ "$1" = classify ] || exit 1
shift
printf '{"protocol":0,"files":['
sep=
for p in "$@"; do printf '%s{"path":"%s","language":"zz","role":"test"}' "$sep" "$p"; sep=,; done
printf ']}'
`
	if err := os.WriteFile(filepath.Join(bin, "assure-adapter-zz"), []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", bin+string(os.PathListSeparator)+os.Getenv("PATH"))
	code, out, stderr := assure("audit", "a.go")
	if code != 1 || out != "" || !strings.Contains(stderr, "ambiguous") || !strings.Contains(stderr, "assure-adapter-zz") {
		t.Fatalf("exit %d stdout %q stderr %q; two adapters disagreeing on a file's role is a broken environment (exit 1) naming the adapters, not a bad argument", code, out, stderr)
	}
}


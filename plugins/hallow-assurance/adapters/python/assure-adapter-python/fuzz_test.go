var (
	fuzzDirGen  = rapid.SampledFrom([]string{".", "app", "app/sub", "src", "src/x", "src/x/y", "srcx", "srcx/y", "lib/src", "tests"})
	fuzzStemGen = rapid.SampledFrom([]string{"parse", "chunker", "é_mod"})
)

// specMirror is <d> from the spec: <dir> with a leading src/ segment
// removed; src itself mirrors to tests/ directly.
func specMirror(dir string) string {
	if dir == "src" {
		return "."
	}
	if rest, ok := strings.CutPrefix(dir, "src/"); ok {
		return rest
	}
	return dir
}

// TestFuzzFilesMatchesSpec: the fuzz files of <unit>/<dir>/<stem>.py are
// <unit>/<dir>/test_<stem>_fuzz.py and <unit>/tests/<d>/test_<stem>_fuzz.py,
// whichever exist. Missing one makes a source look unfuzzed; taking a
// look-alike (an unstripped mirror, a srcx/ strip, a non-fuzz test) runs
// tests that do not fuzz that file.
func TestFuzzFilesMatchesSpec(t *testing.T) {
	base := realTempDir(t)
	rapid.Check(t, func(t *rapid.T) {
		top := tempIn(t, base)
		unitRel := rapid.SampledFrom([]string{".", "svc"}).Draw(t, "unit")
		rootRel := rapid.SampledFrom([]string{".", unitRel}).Draw(t, "root")
		dir, stem := fuzzDirGen.Draw(t, "dir"), fuzzStemGen.Draw(t, "stem")
		name := "test_" + stem + "_fuzz.py"
		src := path.Join(unitRel, dir, stem+".py")
		sibling, mirror := path.Join(unitRel, dir, name), path.Join(unitRel, "tests", specMirror(dir), name)
		files := map[string]string{src: ""}
		var want []string
		for _, p := range []string{sibling, mirror} {
			if rapid.Bool().Draw(t, "exists:"+p) {
				files[p] = ""
				want = append(want, p)
			}
		}
		for _, decoy := range []string{
			path.Join(unitRel, "tests", dir, name),
			path.Join(unitRel, "tests", dir, "test_"+stem+".py"),
			path.Join(unitRel, dir, "test_"+stem+".py"),
			path.Join(unitRel, "test", specMirror(dir), name),
		} {
			if !slices.Contains(want, decoy) && decoy != sibling && decoy != mirror && rapid.Bool().Draw(t, "decoy:"+decoy) {
				files[decoy] = ""
			}
		}
		writeTree(t, top, files)
		root := filepath.Join(top, filepath.FromSlash(rootRel))
		var expect []string
		for _, w := range want {
			expect = append(expect, relSlash(root, filepath.Join(top, filepath.FromSlash(w))))
		}
		slices.Sort(expect)
		expect = slices.Compact(expect)
		got := fuzzFiles(root, filepath.Join(top, filepath.FromSlash(unitRel)), relSlash(root, filepath.Join(top, filepath.FromSlash(src))))
		if !slices.Equal(got, expect) {
			t.Fatalf("fuzzFiles(%s in unit %s, root %s) = %q, want %q", src, unitRel, rootRel, got, expect)
		}
	})
}

// TestFoldSuiteOneCasePerTest: the spec wants one case per test in the
// fuzz files, so Hypothesis tests that are also parameterized fold, with a
// failing instance failing the case, and a collection error stays an
// erroring case.
func TestFoldSuiteOneCasePerTest(t *testing.T) {
	rapid.Check(t, func(t *rapid.T) {
		const file = "tests/test_x_fuzz.py"
		var cases []adapterkit.XMLCase
		want := map[string]string{}
		outcomes := map[string][]instanceOutcome{}
		bodies := map[string][]string{}
		for _, n := range rapid.SliceOfNDistinct(rapid.SampledFrom([]string{"test_a", "TestK::test_b", "test_c"}), 0, 3, rapid.ID[string]).Draw(t, "tests") {
			params := rapid.Bool().Draw(t, "params:"+n)
			for i := range rapid.IntRange(1, 3).Draw(t, "n:"+n) {
				name := n
				if params {
					name = fmt.Sprintf("%s[%d-a::b]", n, i)
				}
				o := rapid.SampledFrom([]instanceOutcome{instPass, instFail, instError, instSkip}).Draw(t, "o")
				body := fmt.Sprintf("BODY %s %d", n, i)
				outcomes[n] = append(outcomes[n], o)
				bodies[n] = append(bodies[n], body)
				c := instanceCase(i, o, body)
				c.Name, c.Classname = name, file
				cases = append(cases, c)
			}
			want[n], _ = foldModel(outcomes[n], bodies[n])
		}
		collect := rapid.Bool().Draw(t, "collectionError")
		if collect {
			cases = append(cases, adapterkit.XMLCase{Name: collectionCase, Classname: file, Error: &adapterkit.XMLText{Message: "collection failure", Body: "E boom"}})
			want[collectionCase] = "errored"
		}
		got := map[string]string{}
		for _, c := range foldSuite(file, rapid.Permutation(cases).Draw(t, "order")) {
			if _, dup := got[c.Name]; dup {
				t.Fatalf("two cases named %s", c.Name)
			}
			if c.Classname != file {
				t.Fatalf("case %s classname %q, want %s", c.Name, c.Classname, file)
			}
			got[c.Name] = outcomeOf(c)
		}
		if fmt.Sprint(got) != fmt.Sprint(want) {
			t.Fatalf("folded %v, want %v; one case per test, parameters folded by D9's rule, collection errors kept", got, want)
		}
	})
}

func TestChangedSourcesOnlySourceRole(t *testing.T) {
	dir := t.TempDir()
	t.Chdir(dir)
	writeTree(t, dir, map[string]string{"app/gen.py": "# Code generated by x. DO NOT EDIT.\nx = 1\n", "app/parse.py": "", "tests/test_p.py": ""})
	c := runContext{sel: map[string][]string{dir: {"app/gen.py", "app/parse.py", "tests/test_p.py"}}}
	got, err := changedSources(c, dir)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"app/parse.py"}; !slices.Equal(got, want) {
		t.Fatalf("changedSources = %q, want %q; fuzz and coverage cover changed non-generated source files only", got, want)
	}
}

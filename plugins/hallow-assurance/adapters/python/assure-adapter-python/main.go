var roles = mustRoles()

func mustRoles() core.Roles {
	r, err := core.NewRoles(map[string]core.RolePatterns{
		"python": {Claims: description.Claims, Patterns: description.Patterns},
	})
	if err != nil {
		panic(err)
	}
	return r
}

type file struct {
	Path     string `json:"path"`
	Language string `json:"language"`
	Role     string `json:"role"`
}

var generatedHeaders = []*regexp.Regexp{
	regexp.MustCompile(`^# Code generated .* DO NOT EDIT\.$`),
	regexp.MustCompile(`^# \*\*\* WARNING: this file was generated by .*\*\*\*$`),
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		_, _ = fmt.Fprintln(stderr, "usage: assure-adapter-python describe | reference | classify <path>... | tools --root <dir> | run <objective> --changed-from <ref> --out <dir>")
		return 2
	}
	var out any
	switch args[0] {
	case "describe":
		out = description
	case "classify":
		files := []file{}
		for _, p := range args[1:] {
			role, claimed, err := classify(p)
			if err != nil {
				_, _ = fmt.Fprintf(stderr, "assure-adapter-python: %v\n", err)
				return 1
			}
			if claimed {
				files = append(files, file{Path: p, Language: "python", Role: role})
			}
		}
		out = map[string]any{"protocol": 0, "files": files}
	case "tools":
		return toolsOp(args[1:], stdout, stderr)
	case "run":
		return runObjective(args[1:], stdout, stderr)
	case "reference":
		if _, err := stdout.Write(reference); err != nil {
			_, _ = fmt.Fprintf(stderr, "assure-adapter-python: %v\n", err)
			return 1
		}
		return 0
	default:
		_, _ = fmt.Fprintf(stderr, "assure-adapter-python: unknown subcommand %q\n", args[0])
		return 2
	}
	if err := json.NewEncoder(stdout).Encode(out); err != nil {
		_, _ = fmt.Fprintf(stderr, "assure-adapter-python: %v\n", err)
		return 1
	}
	return 0
}

func classify(p string) (string, bool, error) {
	role, err := roles.Of(p)
	if err != nil {
		return "", false, err
	}
	if role == core.Unclassified {
		return "", false, nil
	}
	if !strings.HasSuffix(p, ".py") {
		return string(role), true, nil
	}
	gen, err := hasGeneratedHeader(p)
	if err != nil {
		return "", false, err
	}
	if gen {
		return string(core.Generated), true, nil
	}
	return string(role), true, nil
}

func hasGeneratedHeader(p string) (bool, error) {
	f, err := os.Open(p)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	defer func() { _ = f.Close() }()
	if info, err := f.Stat(); err != nil || info.IsDir() {
		return false, err
	}
	r := bufio.NewReader(f)
	for {
		raw, err := r.ReadString('\n')
		if err != nil && !errors.Is(err, io.EOF) {
			return false, fmt.Errorf("%s: %w", p, err)
		}
		line := strings.TrimSuffix(strings.TrimSuffix(raw, "\n"), "\r")
		trimmed := strings.TrimSpace(line)
		if trimmed != "" && !strings.HasPrefix(trimmed, "#") {
			return false, nil
		}
		if matchesGeneratedHeader(line) {
			return true, nil
		}
		if err != nil {
			return false, nil
		}
	}
}

func matchesGeneratedHeader(line string) bool {
	for _, re := range generatedHeaders {
		if re.MatchString(line) {
			return true
		}
	}
	return false
}

func TestLongIndentedCodeLineEndsHeaderSearch(t *testing.T) {
	t.Chdir(t.TempDir())
	src := strings.Repeat(" ", 70<<10) + "import os\n# Code generated by x. DO NOT EDIT.\n"
	if err := os.WriteFile("app.py", []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if got := classifyAll(t, "app.py"); len(got) != 1 || got[0].Role != "source" {
		t.Fatalf("app.py whose first line is 70 KiB of indentation then `import os`, with a header on line 2: got %v, want source; that first line is code, so a header after it must not exempt hand-written code from mutation and coverage", got)
	}
}

func TestLongGeneratedHeaderLine(t *testing.T) {
	t.Chdir(t.TempDir())
	src := "# Code generated " + strings.Repeat("x", 70<<10) + " DO NOT EDIT.\nimport os\n"
	if err := os.WriteFile("models.py", []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if got := classifyAll(t, "models.py"); len(got) != 1 || got[0].Role != "generated" {
		t.Fatalf("models.py whose first line is a 70 KiB `# Code generated ... DO NOT EDIT.` header: got %v, want generated; the spec's header pattern has no length limit", got)
	}
}

// TestUnreadableConfigFailsClosed: configparser.read skips files it cannot
// open, so an unreadable pytest.ini, tox.ini or setup.cfg read as "no
// discovery keys" and the adapter assumed default discovery for a unit that
// may customise it.
func TestUnreadableConfigFailsClosed(t *testing.T) {
	py := testPython(t)
	if os.Geteuid() == 0 {
		t.Skip("root reads a mode-000 file")
	}
	for _, n := range pytestConfigFiles {
		for _, kind := range []string{"mode 000", "directory"} {
			t.Run(n+" "+kind, func(t *testing.T) {
				top := realTempDir(t)
				p := filepath.Join(top, "svc", n)
				writeTree(t, top, map[string]string{"svc/pyproject.toml": "", "svc/" + n: "[pytest]\n[tool:pytest]\n[tool.pytest.ini_options]\n"})
				if kind == "directory" {
					if err := os.Remove(p); err != nil {
						t.Fatal(err)
					}
					if err := os.Mkdir(p, 0o755); err != nil {
						t.Fatal(err)
					}
				} else {
					if err := os.Chmod(p, 0); err != nil {
						t.Fatal(err)
					}
					t.Cleanup(func() { _ = os.Chmod(p, 0o644) })
				}
				msg, err := discoveryRefusal(py, top, filepath.Join(top, "svc"))
				if err != nil {
					t.Fatal(err)
				}
				if !strings.Contains(msg, "svc/"+n) {
					t.Fatalf("unreadable svc/%s (%s): got %q, want an environment message naming it; an unread config may set python_functions, so assuming default discovery fails open", n, kind, msg)
				}
			})
		}
	}
}

// TestFunctionsInsideCompoundStatementsAreListed: the helper walks only
// function and class bodies, so a def under if, try, with, or for is not
// reported. Coverage FN then omits real functions, and a test defined under a
// module-level if (pytest collects it) is never selected by fail-on-base.
func TestFunctionsInsideCompoundStatementsAreListed(t *testing.T) {
	py := testPython(t)
	dir := t.TempDir()
	src := "import sys\n" +
		"if sys:\n" +
		"    def test_if():\n" +
		"        pass\n" +
		"try:\n" +
		"    def g():\n" +
		"        pass\n" +
		"except Exception:\n" +
		"    pass\n" +
		"class C:\n" +
		"    if True:\n" +
		"        def m(self):\n" +
		"            pass\n" +
		"def outer():\n" +
		"    with open(__file__):\n" +
		"        def inner():\n" +
		"            pass\n"
	writeTree(t, dir, map[string]string{"test_c.py": src})
	files, err := describeFiles(py, dir, []string{"test_c.py"})
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, f := range files["test_c.py"].Functions {
		names = append(names, f.Name)
	}
	slices.Sort(names)
	if want := []string{"C.m", "g", "outer", "outer.inner", "test_if"}; !slices.Equal(names, want) {
		t.Fatalf("functions = %q, want %q; every def is a function coverage must account for, wherever its enclosing block", names, want)
	}
	if tests := files["test_c.py"].Tests; len(tests) != 1 || tests[0].Name != "test_if" {
		t.Fatalf("tests = %+v, want test_if; pytest collects a module-level test defined under if", tests)
	}
}

// pytest 9 writes a test that fails in its call and then errors in teardown
// as two <testcase> elements with the same name, one <failure> and one
// <error> (recorded from pytest 9 with -o junit_family=xunit1).
const failThenTeardownError = `<?xml version="1.0" encoding="utf-8"?><testsuites name="pytest tests"><testsuite name="pytest" errors="1" failures="1" skipped="0" tests="3">
<testcase classname="tests.test_t" name="test_pass" file="tests/test_t.py" line="1" time="0.000" />
<testcase classname="tests.test_t" name="test_fail_and_td" file="tests/test_t.py" line="5" time="0.000"><failure message="assert False">E   assert False</failure></testcase>
<testcase classname="tests.test_t" name="test_fail_and_td" file="tests/test_t.py" line="5" time="0.000"><error message="failed on teardown with &quot;RuntimeError: teardown boom&quot;">E   RuntimeError: teardown boom</error></testcase>
</testsuite></testsuites>`

// TestCallFailureWithTeardownErrorIsOneCase: the spec's conversion scenario
// counts failed tests, and one test that failed then errored in teardown is
// one failed test. Two same-named cases also give assure two results for one
// test identity.
func TestCallFailureWithTeardownErrorIsOneCase(t *testing.T) {
	top := realTempDir(t)
	writeTree(t, top, map[string]string{"tests/test_t.py": "", "pytest.xml": failThenTeardownError})
	r, err := readPytestReport(filepath.Join(top, "pytest.xml"))
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	failing := 0
	for _, s := range toJUnit(top, top, top, r) {
		for _, c := range s.Cases {
			names = append(names, c.Name)
			if c.Failure != nil || c.Error != nil {
				failing++
			}
		}
	}
	if want := []string{"test_fail_and_td", "test_pass"}; !slices.Equal(names, want) || failing != 1 {
		t.Fatalf("cases %q with %d failing, want %q with 1; failures plus errors must equal failed tests, and test_fail_and_td is one test (merge the teardown error into its case)", names, failing, want)
	}
}

// pytest 9 writes a test whose setup errors and whose teardown then errors
// too as one <testcase> holding two <error> elements (recorded from pytest 9,
// xunit1).
const setupThenTeardownError = `<?xml version="1.0" encoding="utf-8"?><testsuites name="pytest tests"><testsuite name="pytest" errors="2" failures="0" skipped="0" tests="1">
<testcase classname="tests.test_t" name="test_setup_and_td" file="tests/test_t.py" line="9" time="0.000"><error message="failed on setup with &quot;RuntimeError: setup boom&quot;">E   RuntimeError: setup boom</error><error message="failed on teardown with &quot;RuntimeError: teardown boom&quot;">E   RuntimeError: teardown boom</error></testcase>
</testsuite></testsuites>`

// TestSetupErrorSurvivesTeardownError: the setup error is why the test never
// ran; keeping only the teardown error that follows it shows the developer a
// symptom and hides the cause.
func TestSetupErrorSurvivesTeardownError(t *testing.T) {
	top := realTempDir(t)
	writeTree(t, top, map[string]string{"tests/test_t.py": "", "pytest.xml": setupThenTeardownError})
	r, err := readPytestReport(filepath.Join(top, "pytest.xml"))
	if err != nil {
		t.Fatal(err)
	}
	suites := toJUnit(top, top, top, r)
	if len(suites) != 1 || len(suites[0].Cases) != 1 || suites[0].Cases[0].Error == nil {
		t.Fatalf("converted %+v, want one erroring case", suites)
	}
	e := suites[0].Cases[0].Error
	if text := e.Message + "\n" + e.Body; !strings.Contains(text, "setup boom") || !strings.Contains(text, "teardown boom") {
		t.Fatalf("error %q / %q; both of the case's <error> elements must reach the evidence, the setup error above all", e.Message, e.Body)
	}
}

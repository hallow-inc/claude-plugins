func fuzzSuites(t *testing.T, out string, resp runResponse) map[string][]ev.Case {
	t.Helper()
	if resp.Environment != nil {
		t.Fatalf("environment %q", resp.Environment.Message)
	}
	if want := []evidence{{Type: "fuzz.run", Path: "fuzz.xml"}}; !slices.Equal(resp.Evidence, want) {
		t.Fatalf("evidence %+v, want %+v", resp.Evidence, want)
	}
	data, err := os.ReadFile(filepath.Join(out, "fuzz.xml"))
	if err != nil {
		t.Fatal(err)
	}
	j, err := ev.ParseJUnit(data)
	if err != nil {
		t.Fatalf("assure's fuzz reader (ParseJUnit) rejects the evidence: %v\n%s", err, data)
	}
	got := map[string][]ev.Case{}
	for _, s := range j.Suites {
		if len(s.Properties) != 1 || s.Properties[0].Name != "assure.source" || s.Properties[0].Value != s.Name {
			t.Fatalf("suite %s properties %+v; each suite carries its source file as its only assure.source property", s.Name, s.Properties)
		}
		if _, dup := got[s.Name]; dup {
			t.Fatalf("two suites for %s", s.Name)
		}
		got[s.Name] = s.Cases
	}
	return got
}

func outcomesOf(cases []ev.Case) map[string]ev.Outcome {
	out := map[string]ev.Outcome{}
	for _, c := range cases {
		out[c.Name] = c.Outcome
	}
	return out
}

// TestIntegrationFuzzScenarios runs the four spec scenarios in one repository:
// mirrored and sibling fuzz files, a source without one, and a failing
// property; a generated or unchanged source gets no suite.
func TestIntegrationFuzzScenarios(t *testing.T) {
	top := realPyRepo(t, fuzzRepoFiles)
	writeTree(t, top, map[string]string{
		"src/transcription/chunker.py": "def chunk(s, n):\n    return [s[i:i + n] for i in range(0, len(s), n)] or []\n",
		"app/parse.py":                 "def parse(s):\n    return int(s.strip())\n",
		"app/lonely.py":                "LONELY = 2\n",
		"app/bad.py":                   "def bad(n):\n    return n + 0\n",
		"app/gen.py":                   "# Code generated by tool. DO NOT EDIT.\nG = 2\n",
	})
	out := t.TempDir()
	got := fuzzSuites(t, out, runObjectiveIn(t, "VER-ROBUST-FUZZ", out))
	want := map[string]map[string]ev.Outcome{
		"src/transcription/chunker.py": {"tests/transcription/test_chunker_fuzz.py.test_roundtrip": ev.Passed, "tests/transcription/test_chunker_fuzz.py.test_sizes": ev.Passed},
		"app/parse.py":                 {"app/test_parse_fuzz.py.test_parse_any": ev.Passed},
		"app/lonely.py":                {},
		"app/bad.py":                   {"app/test_bad_fuzz.py.test_small": ev.Failed},
	}
	if names := slices.Sorted(maps.Keys(got)); !slices.Equal(names, slices.Sorted(maps.Keys(want))) {
		t.Fatalf("suites %q, want one per changed non-generated source file %q", names, slices.Sorted(maps.Keys(want)))
	}
	for src, w := range want {
		if g := outcomesOf(got[src]); !maps.Equal(g, w) {
			t.Fatalf("suite %s cases %v, want %v (Mirrored fuzz file: two cases; Sibling fuzz file: one; Missing fuzz file: zero; Failing property is a failed case)", src, g, w)
		}
	}
}

func TestIntegrationFuzzSeedFixesDraws(t *testing.T) {
	top := realPyRepo(t, fuzzRepoFiles)
	writeTree(t, top, map[string]string{"src/transcription/chunker.py": "def chunk(s, n):\n    return [s[i:i + n] for i in range(0, len(s), n)] or []\n"})
	var draws [2]string
	for i := range draws {
		log := filepath.Join(t.TempDir(), "draws")
		t.Setenv("ASSURE_DRAW_LOG", log)
		out := t.TempDir()
		fuzzSuites(t, out, runObjectiveIn(t, "VER-ROBUST-FUZZ", out))
		data, err := os.ReadFile(log)
		if err != nil {
			t.Fatal(err)
		}
		draws[i] = string(data)
	}
	if draws[0] != draws[1] || draws[0] == "" {
		t.Fatalf("two fuzz runs on one commit drew different inputs (%d vs %d bytes); the seed must fix Hypothesis's draws so a failure replays", len(draws[0]), len(draws[1]))
	}
}

const decideSrc = `def deco(f):
    return f


@deco
def decide(x):
    if x:
        return 1
    return 2


class Reader:
    def parse(self, s):
        return int(s)

    def unused(self):
        return 0


def outer():
    def inner():
        return 1

    return inner()
`

var coverageRepoFiles = map[string]string{
	"app/decide.py":        decideSrc,
	"app/unimported.py":    "def f():\n    return 1\n",
	"lib/solo.py":          "X = 1\n",
	"tests/test_decide.py": "from app.decide import Reader, decide\n\n\ndef test_decide():\n    assert decide(1) == 1\n\n\ndef test_parse():\n    assert Reader().parse(\"3\") == 3\n",
	".coveragerc":          "[run]\nomit =\n    app/*\n    lib/*\n",
}

func coverageRepo(t *testing.T) string {
	top := realPyRepo(t, coverageRepoFiles)
	data, err := os.ReadFile(filepath.Join(top, "pyproject.toml"))
	if err != nil {
		t.Fatal(err)
	}
	writeTree(t, top, map[string]string{"pyproject.toml": string(data) + "\n[tool.coverage.run]\nomit = [\"app/decide.py\", \"lib/*\"]\n"})
	git(t, top, "commit", "-q", "-am", "adopter omits")
	writeTree(t, top, map[string]string{
		"app/decide.py":     decideSrc + "# changed\n",
		"app/unimported.py": "def f():\n    return 2\n",
		"lib/solo.py":       "X = 2\n",
	})
	return top
}

func lcovOf(t *testing.T, out string, resp runResponse) ([]byte, map[string]ev.LCOVFile) {
	t.Helper()
	if resp.Environment != nil {
		t.Fatalf("environment %q", resp.Environment.Message)
	}
	if want := []evidence{{Type: "coverage.resolution", Path: "coverage.lcov"}}; !slices.Equal(resp.Evidence, want) {
		t.Fatalf("evidence %+v, want %+v", resp.Evidence, want)
	}
	data, err := os.ReadFile(filepath.Join(out, "coverage.lcov"))
	if err != nil {
		t.Fatal(err)
	}
	files, err := ev.ParseLCOV(data)
	if err != nil {
		t.Fatalf("assure's LCOV reader rejects the evidence: %v\n%s", err, data)
	}
	byPath := map[string]ev.LCOVFile{}
	for _, f := range files {
		byPath[f.Path] = f
	}
	return data, byPath
}

type fnWant struct{ start, end, hits int }

// TestIntegrationCoverage covers "Function span", "Method name" and
// "Deterministic", with the adopter omitting every changed file in both
// .coveragerc and pyproject.toml, and with files no test imports.
func TestIntegrationCoverage(t *testing.T) {
	coverageRepo(t)
	out1, out2 := t.TempDir(), t.TempDir()
	data1, files := lcovOf(t, out1, runObjectiveIn(t, "VER-COVERAGE-RESOLUTION", out1))
	data2, _ := lcovOf(t, out2, runObjectiveIn(t, "VER-COVERAGE-RESOLUTION", out2))
	if string(data1) != string(data2) {
		t.Fatalf("two coverage runs on one commit differ:\n%s\n----\n%s\nspec \"Deterministic\"", data1, data2)
	}
	if names := slices.Sorted(maps.Keys(files)); !slices.Equal(names, []string{"app/decide.py", "app/unimported.py", "lib/solo.py"}) {
		t.Fatalf("LCOV records for %q; every changed source file has one, though the adopter's omit covers all three and no test imports two of them; a missing record would read as nothing to resolve\n%s", names, data1)
	}
	decide := files["app/decide.py"]
	fns := map[string]fnWant{}
	for _, fn := range decide.Functions {
		fns[fn.Name] = fnWant{fn.Start, fn.End, fn.Hits}
	}
	want := map[string]fnWant{"deco": {1, 2, 1}, "decide": {6, 9, 1}, "Reader.parse": {13, 14, 1}, "Reader.unused": {16, 17, 0}, "outer": {20, 24, 0}, "outer.inner": {21, 22, 0}}
	if !maps.Equal(fns, want) {
		t.Fatalf("FN records %v\nwant %v\n\"Function span\": def line (not the decorator) to the last line; \"Method name\": Class.method and outer.inner", fns, want)
	}
	for line, hits := range map[int]int{2: 1, 7: 1, 8: 1, 9: 0, 14: 1, 17: 0, 22: 0, 24: 0} {
		if got, ok := decide.Lines[line]; !ok || got != hits {
			t.Fatalf("app/decide.py DA %d = %d (present %v), want %d\n%s", line, got, ok, hits, data1)
		}
	}
	checkUncoveredAndClamped(t, files)
}

func checkUncoveredAndClamped(t *testing.T, files map[string]ev.LCOVFile) {
	for _, p := range []string{"app/unimported.py", "lib/solo.py"} {
		f := files[p]
		if len(f.Lines) == 0 {
			t.Fatalf("%s has no DA records; an unimported changed file must show its lines uncovered", p)
		}
		for l, h := range f.Lines {
			if h != 0 {
				t.Fatalf("%s DA %d = %d; nothing imports it", p, l, h)
			}
		}
	}
	for _, f := range files {
		for l, h := range f.Lines {
			if h != 0 && h != 1 {
				t.Fatalf("%s DA %d = %d; counts are clamped to 0 or 1", f.Path, l, h)
			}
		}
	}
}

// TestIntegrationFuzzWithoutFuzzFilesRunsNothing: a changed source with no
// fuzz file gets its empty suite without starting pytest; running pytest
// with no file arguments would run the unit's whole suite, slowing every
// fuzz check and failing it on any unrelated suite problem.
func TestIntegrationFuzzWithoutFuzzFilesRunsNothing(t *testing.T) {
	marker := filepath.Join(t.TempDir(), "ran")
	t.Setenv("ASSURE_PYTEST_MARKER", marker)
	top := realPyRepo(t, map[string]string{"conftest.py": "import os\n\n\ndef pytest_configure(config):\n    open(os.environ[\"ASSURE_PYTEST_MARKER\"], \"w\").close()\n"})
	writeTree(t, top, map[string]string{"app/parse.py": "def parse(s):\n    return int(s, 10)\n"})
	out := t.TempDir()
	got := fuzzSuites(t, out, runObjectiveIn(t, "VER-ROBUST-FUZZ", out))
	if cases, ok := got["app/parse.py"]; !ok || len(cases) != 0 || len(got) != 1 {
		t.Fatalf("suites %v; app/parse.py has no fuzz file, so one suite with zero cases", got)
	}
	if adapterkit.Exists(marker) {
		t.Fatal("pytest started though no fuzz file exists; it would run the unit's whole test suite as fuzz targets")
	}
}

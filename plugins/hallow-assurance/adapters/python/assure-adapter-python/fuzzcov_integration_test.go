const chunkerFuzz = `import os

from hypothesis import given, settings, strategies as st

from src.transcription.chunker import chunk


@settings(max_examples=30, database=None)
@given(st.text(), st.integers(1, 5))
def test_roundtrip(s, n):
    log = os.environ.get("ASSURE_DRAW_LOG")
    if log:
        with open(log, "a") as f:
            f.write("%r %d\n" % (s, n))
    assert "".join(chunk(s, n)) == s


@given(st.text(), st.integers(1, 5))
def test_sizes(s, n):
    assert all(len(c) <= n for c in chunk(s, n))
`

